CREATE TABLE `InitializationCase` (
    `id` VARCHAR(191) NOT NULL,
    `communityId` VARCHAR(191) NOT NULL,
    `cutoverDate` DATETIME(3) NULL,
    `historyFrom` DATETIME(3) NULL,
    `historyTo` DATETIME(3) NULL,
    `status` VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    `appliedAt` DATETIME(3) NULL,
    `journalEntryId` VARCHAR(191) NULL,
    `createdById` VARCHAR(191) NOT NULL,
    `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    `updatedAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    UNIQUE INDEX `InitializationCase_communityId_key`(`communityId`),
    UNIQUE INDEX `InitializationCase_journalEntryId_key`(`journalEntryId`),
    INDEX `InitializationCase_status_cutoverDate_idx`(`status`, `cutoverDate`),
    PRIMARY KEY (`id`),
    CONSTRAINT `InitializationCase_communityId_fkey` FOREIGN KEY (`communityId`) REFERENCES `Community`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT `InitializationCase_journalEntryId_fkey` FOREIGN KEY (`journalEntryId`) REFERENCES `JournalEntry`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE TABLE `InitializationRow` (
    `id` VARCHAR(191) NOT NULL,
    `initializationId` VARCHAR(191) NOT NULL,
    `kind` VARCHAR(30) NOT NULL,
    `externalRef` VARCHAR(160) NOT NULL,
    `propertyId` VARCHAR(191) NULL,
    `vendorId` VARCHAR(191) NULL,
    `eventDate` DATETIME(3) NOT NULL,
    `description` VARCHAR(500) NOT NULL,
    `amount` DECIMAL(18,2) NOT NULL,
    `currency` ENUM('VES','USD','EUR') NOT NULL,
    `metadata` JSON NULL,
    `operationalEntityType` VARCHAR(40) NULL,
    `operationalEntityId` VARCHAR(191) NULL,
    `status` VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    `updatedAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    UNIQUE INDEX `InitializationRow_initializationId_kind_externalRef_key`(`initializationId`, `kind`, `externalRef`),
    INDEX `InitializationRow_initializationId_kind_status_idx`(`initializationId`, `kind`, `status`),
    INDEX `InitializationRow_propertyId_eventDate_idx`(`propertyId`, `eventDate`),
    INDEX `InitializationRow_vendorId_eventDate_idx`(`vendorId`, `eventDate`),
    PRIMARY KEY (`id`),
    CONSTRAINT `InitializationRow_initializationId_fkey` FOREIGN KEY (`initializationId`) REFERENCES `InitializationCase`(`id`) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT `InitializationRow_propertyId_fkey` FOREIGN KEY (`propertyId`) REFERENCES `Property`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT `InitializationRow_vendorId_fkey` FOREIGN KEY (`vendorId`) REFERENCES `Vendor`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
