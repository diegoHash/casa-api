CREATE TABLE `VendorPayable` (
  `id` VARCHAR(191) NOT NULL,
  `communityId` VARCHAR(191) NOT NULL,
  `vendorId` VARCHAR(191) NULL,
  `category` ENUM('SECURITY', 'ELEVATOR_MAINTENANCE', 'WASTE_COLLECTION', 'GARDENING', 'UTILITIES', 'PAYROLL', 'PROFESSIONAL_FEES', 'REPAIRS_MATERIALS', 'OTHER') NOT NULL,
  `supplierName` VARCHAR(220) NOT NULL,
  `supplierDocument` VARCHAR(40) NULL,
  `description` VARCHAR(500) NOT NULL,
  `invoiceNumber` VARCHAR(100) NULL,
  `issueDate` DATETIME(3) NOT NULL,
  `dueDate` DATETIME(3) NOT NULL,
  `amount` DECIMAL(18,2) NOT NULL,
  `amountPaid` DECIMAL(18,2) NOT NULL DEFAULT 0,
  `currency` ENUM('VES', 'USD', 'EUR') NOT NULL,
  `status` ENUM('PENDING', 'PARTIALLY_PAID', 'PAID', 'VOID') NOT NULL DEFAULT 'PENDING',
  `notes` VARCHAR(1000) NULL,
  `expenseAccountId` VARCHAR(191) NULL,
  `liabilityAccountId` VARCHAR(191) NULL,
  `paymentAccountId` VARCHAR(191) NULL,
  `initialJournalEntryId` VARCHAR(191) NULL,
  `paymentJournalEntryId` VARCHAR(191) NULL,
  `paidAt` DATETIME(3) NULL,
  `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updatedAt` DATETIME(3) NOT NULL,

  PRIMARY KEY (`id`),
  UNIQUE INDEX `VendorPayable_initialJournalEntryId_key` (`initialJournalEntryId`),
  UNIQUE INDEX `VendorPayable_paymentJournalEntryId_key` (`paymentJournalEntryId`),
  INDEX `VendorPayable_communityId_status_dueDate_idx` (`communityId`, `status`, `dueDate`),
  INDEX `VendorPayable_communityId_category_status_idx` (`communityId`, `category`, `status`),
  INDEX `VendorPayable_vendorId_dueDate_idx` (`vendorId`, `dueDate`),
  CONSTRAINT `VendorPayable_communityId_fkey` FOREIGN KEY (`communityId`) REFERENCES `Community`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `VendorPayable_vendorId_fkey` FOREIGN KEY (`vendorId`) REFERENCES `Vendor`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `VendorPayable_expenseAccountId_fkey` FOREIGN KEY (`expenseAccountId`) REFERENCES `LedgerAccount`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `VendorPayable_liabilityAccountId_fkey` FOREIGN KEY (`liabilityAccountId`) REFERENCES `LedgerAccount`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `VendorPayable_paymentAccountId_fkey` FOREIGN KEY (`paymentAccountId`) REFERENCES `LedgerAccount`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `VendorPayable_initialJournalEntryId_fkey` FOREIGN KEY (`initialJournalEntryId`) REFERENCES `JournalEntry`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `VendorPayable_paymentJournalEntryId_fkey` FOREIGN KEY (`paymentJournalEntryId`) REFERENCES `JournalEntry`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
